  function t(path, params) {
    var keys = path.split('.')
    var obj = (messages[locale] || messages['en-US'])
    for (var i = 0; i < keys.length; i++) {
      if (!obj) return path
      obj = obj[keys[i]]
    }
    if (typeof obj === 'string') {
      if (params) {
        for (var k in params) {
          obj = obj.replace('{' + k + '}', params[k])
        }
      }
      return obj
    }
    return path
  }

  window.__ = t
  window.__locale = locale
  window.__setLocale = function (l) {
    locale = l
    try { localStorage.setItem(STORAGE_KEY, l) } catch (e) {}
  }
